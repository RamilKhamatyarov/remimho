package ru.rkhamatyarov.tunnel

import ru.rkhamatyarov.determinism.Trace
import ru.rkhamatyarov.determinism.TraceEntry
import ru.rkhamatyarov.proto.TapeHeader
import ru.rkhamatyarov.proto.TapeRecord
import java.io.BufferedInputStream
import java.io.BufferedOutputStream
import java.io.Closeable
import java.io.InputStream
import java.io.OutputStream
import java.security.MessageDigest

/** Append-only length-delimited tape writer. Closing appends a final step marker. */
class TunnelTapeWriter(
    output: OutputStream,
    val header: TapeHeader,
    private val markIntervalSteps: Long = DEFAULT_MARK_INTERVAL,
) : Closeable {
    private val stream = BufferedOutputStream(output)
    private var sequence = 0L
    private var lastStep = 0L
    private var lastMarkedStep = -1L
    private var closed = false

    init {
        validateHeader(header)
        require(markIntervalSteps > 0L) { "markIntervalSteps must be positive" }
        header.writeDelimitedTo(stream)
    }

    @Synchronized
    fun append(record: TapeRecord) {
        check(!closed) { "tape writer is closed" }
        require(record.kind != TapeRecord.Kind.MARK) { "MARK records are generated by the writer" }
        val numberedRecord = record.toBuilder().setSeq(sequence + 1).build()
        TapeRecords.validate(numberedRecord, sequence + 1, lastStep)
        numberedRecord.writeDelimitedTo(stream)
        sequence = numberedRecord.seq
        lastStep = numberedRecord.step
        if (lastStep > 0 &&
            lastStep % markIntervalSteps == 0L &&
            lastMarkedStep != lastStep &&
            numberedRecord.kind != TapeRecord.Kind.MARK
        ) {
            appendMark(lastStep)
        }
    }

    @Synchronized
    override fun close() {
        if (closed) return
        if (lastMarkedStep != lastStep) appendMark(lastStep)
        stream.flush()
        stream.close()
        closed = true
    }

    /** Pins the step count reached; used by deterministic scenario scripts. */
    @Synchronized
    fun mark(step: Long) {
        check(!closed) { "tape writer is closed" }
        require(step >= lastStep) { "mark step $step is before the last input step $lastStep" }
        if (lastMarkedStep != step) appendMark(step)
    }

    private fun appendMark(step: Long) {
        TapeRecord.newBuilder()
            .setKind(TapeRecord.Kind.MARK)
            .setSeq(sequence + 1)
            .setStep(step)
            .build()
            .also {
                it.writeDelimitedTo(stream)
                sequence++
                lastMarkedStep = step
                lastStep = step
            }
    }

    companion object {
        const val FORMAT_VERSION = 1
        private const val DEFAULT_MARK_INTERVAL = 120L
    }
}

/** Reads and validates a full tape before exposing records to replay. */
object TunnelTapeReader {
    fun read(
        input: InputStream,
        supportedPhysicsVersions: Set<String>,
        supportedSubstrates: Set<String>,
    ): TunnelTape {
        val stream = BufferedInputStream(input)
        val header = TapeHeader.parseDelimitedFrom(stream) ?: error("missing tape header")
        validateHeader(header)
        require(header.physicsVersion in supportedPhysicsVersions) {
            "unsupported physics version '${header.physicsVersion}'"
        }
        require(header.substrateId in supportedSubstrates) {
            "unsupported substrate '${header.substrateId}'"
        }

        val records = ArrayList<TapeRecord>()
        var previousStep = 0L
        var expectedSeq = 1L
        while (true) {
            val record = TapeRecord.parseDelimitedFrom(stream) ?: break
            TapeRecords.validate(record, expectedSeq, previousStep)
            records += record
            expectedSeq++
            previousStep = record.step
        }
        return TunnelTape(header, records)
    }
}

private fun validateHeader(header: TapeHeader) {
    require(header.formatVersion == TunnelTapeWriter.FORMAT_VERSION) {
        "unsupported format version ${header.formatVersion}"
    }
    require(header.physicsVersion.isNotBlank()) { "missing physics version" }
    require(header.substrateId.isNotBlank()) { "missing substrate id" }
    require(header.stepDurationNs in 1L..MAX_STEP_DURATION_NS) {
        "invalid step duration ${header.stepDurationNs}"
    }
    require(header.widthRaw in 1L..MAX_DIMENSION_RAW) { "invalid width raw value ${header.widthRaw}" }
    require(header.heightRaw in 1L..MAX_DIMENSION_RAW) { "invalid height raw value ${header.heightRaw}" }
    require(header.depthRaw in 1L..MAX_DIMENSION_RAW) { "invalid depth raw value ${header.depthRaw}" }
    require(!header.initialState.isEmpty) { "missing initial state" }
}

data class TunnelTape(
    val header: TapeHeader,
    val records: List<TapeRecord>,
)

/** Reduces each logical step once with that step's inputs, then records the resulting state hash. */
fun <S> TunnelTape.replay(
    initial: S,
    reduceStep: (state: S, step: Long, inputs: List<TapeRecord>) -> S,
    hash: (S) -> Long,
): Trace {
    var state = initial
    val recordsByStep =
        records.asSequence()
            .filter { it.kind != TapeRecord.Kind.MARK }
            .groupBy(TapeRecord::getStep)
    val finalStep = records.maxOfOrNull(TapeRecord::getStep) ?: 0L
    val entries = ArrayList<TraceEntry>(finalStep.coerceAtMost(Int.MAX_VALUE.toLong()).toInt())

    for (step in 1L..finalStep) {
        state = reduceStep(state, step, recordsByStep[step].orEmpty())
        entries += TraceEntry(step, hash(state))
    }

    return Trace(
        mapOf(
            Trace.KEY_SOURCE to sha256(serializedBytes()),
            Trace.KEY_KIND to "tunnel-tape",
            Trace.KEY_PHYSICS to header.physicsVersion,
            Trace.KEY_SUBSTRATE to header.substrateId,
        ),
        entries,
    )
}

private fun TunnelTape.serializedBytes(): ByteArray =
    java.io.ByteArrayOutputStream().also { output ->
        header.writeDelimitedTo(output)
        records.forEach { it.writeDelimitedTo(output) }
    }.toByteArray()

/** Replays the tape through the input-only tunnel reducer scaffold. */
fun TunnelTape.replayTunnel(
    initial: TunnelState,
    rules: TunnelRules = initial.rules,
): Trace {
    require(header.physicsVersion == rules.physicsVersion) {
        "tape physics version '${header.physicsVersion}' does not match rules '${rules.physicsVersion}'"
    }
    require(header.substrateId == TunnelMath.SUBSTRATE_ID) {
        "unsupported tunnel substrate '${header.substrateId}'"
    }
    require(header.stepDurationNs == rules.stepDurationNs) { "tape step duration does not match rules" }
    val sameDimensions =
        header.widthRaw == rules.width.raw &&
            header.heightRaw == rules.height.raw &&
            header.depthRaw == rules.depth.raw
    require(sameDimensions) { "tape dimensions do not match rules" }
    return replay(
        initial,
        { state, _, stepInputs -> reduceTunnel(state, stepInputs.map(TapeRecord::toTunnelInput), rules) },
        TunnelStateEncoder::hashOf,
    )
}

private fun TapeRecord.toTunnelInput(): TunnelInput =
    when (kind) {
        TapeRecord.Kind.PADDLE_TARGET ->
            TunnelInput.PaddleTarget(
                when (paddleTarget.side) {
                    ru.rkhamatyarov.proto.PaddleTarget.Side.A -> TunnelSide.A
                    ru.rkhamatyarov.proto.PaddleTarget.Side.B -> TunnelSide.B
                    else -> error("invalid paddle side at seq $seq")
                },
                TunnelVector2(TunnelScalar(paddleTarget.xRaw), TunnelScalar(paddleTarget.yRaw)),
            )
        TapeRecord.Kind.SERVE ->
            TunnelInput.Serve(
                TunnelVector3(TunnelScalar(serve.vxRaw), TunnelScalar(serve.vyRaw), TunnelScalar(serve.vzRaw)),
            )
        TapeRecord.Kind.RESET -> TunnelInput.Reset
        else -> error("record kind $kind is not a tunnel input at seq $seq")
    }

private object TapeRecords {
    fun validate(
        record: TapeRecord,
        expectedSeq: Long,
        previousStep: Long,
    ) {
        require(record.seq == expectedSeq) { "expected seq $expectedSeq but found ${record.seq}" }
        require(record.step >= previousStep) {
            "decreasing step at seq ${record.seq}: ${record.step} < $previousStep"
        }
        require(record.kind == TapeRecord.Kind.MARK || record.step > 0L) {
            "input record at seq ${record.seq} must target a positive step"
        }
        when (record.kind) {
            TapeRecord.Kind.PADDLE_TARGET -> {
                require(record.hasPaddleTarget()) {
                    "missing paddle target at seq ${record.seq}"
                }
                require(
                    record.paddleTarget.side == ru.rkhamatyarov.proto.PaddleTarget.Side.A ||
                        record.paddleTarget.side == ru.rkhamatyarov.proto.PaddleTarget.Side.B,
                ) { "invalid paddle side at seq ${record.seq}" }
            }
            TapeRecord.Kind.SERVE -> require(record.hasServe()) { "missing serve payload at seq ${record.seq}" }
            TapeRecord.Kind.RESET, TapeRecord.Kind.MARK ->
                require(
                    record.payloadCase == TapeRecord.PayloadCase.PAYLOAD_NOT_SET,
                ) { "unexpected payload at seq ${record.seq}" }
            else -> throw IllegalArgumentException("unknown record kind ${record.kindValue} at seq ${record.seq}")
        }
    }
}

private fun sha256(bytes: ByteArray): String =
    MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

private const val MAX_STEP_DURATION_NS = 1_000_000_000L
private const val MAX_DIMENSION_RAW = TunnelRules.MAX_DIMENSION_RAW
